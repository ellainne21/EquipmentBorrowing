using EquipmentBorrowing.Application.Interfaces;
using EquipmentBorrowing.Application.Services;
using EquipmentBorrowing.Contracts;
using Microsoft.AspNetCore.Mvc;

namespace EquipmentBorrowing.Api.Controllers;

// API-02 to API-06 and API-15. UC-03, 06, 07, 12, 13, 14.
[ApiController]
[Route("api/v1/students")]
[Produces("application/json")]
[ProducesResponseType<ErrorResponse>(StatusCodes.Status500InternalServerError)]
public class StudentsController : ApiControllerBase
{
    private readonly StudentQueryService _query;
    private readonly IStudentRepository _students;
    private readonly IBorrowingRepository _borrowings;
    private readonly RegisterStudentService _register;
    private readonly UpdateStudentService _update;
    private readonly ChangeStudentEligibilityService _eligibility;

    public StudentsController(
        StudentQueryService query,
        IStudentRepository students,
        IBorrowingRepository borrowings,
        RegisterStudentService register,
        UpdateStudentService update,
        ChangeStudentEligibilityService eligibility)
    {
        _query = query;
        _students = students;
        _borrowings = borrowings;
        _register = register;
        _update = update;
        _eligibility = eligibility;
    }

    // API-02
    [HttpGet]
    [ProducesResponseType<List<StudentDto>>(StatusCodes.Status200OK)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status400BadRequest)]
    public async Task<IActionResult> List([FromQuery] string? search, CancellationToken cancellationToken)
    {
        var result = await _query.SearchAsync(search, cancellationToken);
        if (!result.IsSuccess) return ServerFailure(result.ErrorMessage);

        return Ok(result.Items.Select(s => s.ToDto()).ToList());
    }

    // API-03
    [HttpGet("{id}")]
    [ProducesResponseType<StudentDto>(StatusCodes.Status200OK)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status400BadRequest)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> Get(int id, CancellationToken cancellationToken)
    {
        var student = await _students.GetByIdAsync(id, cancellationToken);
        if (student is null) return Missing("The student was not found.");

        return Ok(student.ToDto());
    }

    // API-04: the new student is eligible (BR-02). The id is generated by PostgreSQL.
    [HttpPost]
    [ProducesResponseType<StudentDto>(StatusCodes.Status201Created)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status400BadRequest)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status409Conflict)]
    public async Task<IActionResult> Create([FromBody] CreateStudentRequest request, CancellationToken cancellationToken)
    {
        var problem = RequiredText(request.StudentNumber, "Student number", 50)
            ?? RequiredText(request.FullName, "Full name", 200)
            ?? OptionalText(request.Contact, "Contact", 200);
        if (problem is not null) return BadInput(problem);

        var result = await _register.ExecuteAsync(request.StudentNumber, request.FullName, request.Contact, cancellationToken);
        if (!result.IsSuccess) return FromOperation(result);

        return await AfterSave(async () =>
        {
            var student = await _students.GetByIdAsync(result.EntityId!.Value, cancellationToken);
            if (student is null) return ServerFailure("The student was saved, but could not be read back. Refresh to see the current data.");

            return CreatedAtAction(nameof(Get), new { id = student.Id }, student.ToDto());
        });
    }

    // API-05: update sends all editable fields. The id never changes, so history stays linked (BR-03, BR-14).
    [HttpPut("{id}")]
    [ProducesResponseType<StudentDto>(StatusCodes.Status200OK)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status400BadRequest)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status404NotFound)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status409Conflict)]
    public async Task<IActionResult> Update(int id, [FromBody] UpdateStudentRequest request, CancellationToken cancellationToken)
    {
        var problem = RequiredText(request.StudentNumber, "Student number", 50)
            ?? RequiredText(request.FullName, "Full name", 200)
            ?? OptionalText(request.Contact, "Contact", 200);
        if (problem is not null) return BadInput(problem);

        if (await _students.GetByIdAsync(id, cancellationToken) is null)
            return Missing("The student was not found.");

        var result = await _update.ExecuteAsync(id, request.StudentNumber, request.FullName, request.Contact, cancellationToken);
        if (!result.IsSuccess) return FromOperation(result);

        return await AfterSave(async () =>
        {
            var student = await _students.GetByIdAsync(id, cancellationToken);
            return student is null ? Missing("The student was not found.") : Ok(student.ToDto());
        });
    }

    // API-06: setting the value the student already has is a no-op that returns 200.
    [HttpPatch("{id}/eligibility")]
    [ProducesResponseType<StudentDto>(StatusCodes.Status200OK)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status400BadRequest)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> SetEligibility(int id, [FromBody] SetEligibilityRequest request, CancellationToken cancellationToken)
    {
        if (request.IsEligible is null) return BadInput("isEligible is required and must be true or false.");

        var student = await _students.GetByIdAsync(id, cancellationToken);
        if (student is null) return Missing("The student was not found.");

        if (student.IsAllowedToBorrow == request.IsEligible.Value) return Ok(student.ToDto());

        var result = await _eligibility.ExecuteAsync(id, request.IsEligible.Value, cancellationToken);
        if (!result.IsSuccess) return FromOperation(result);

        return await AfterSave(async () =>
        {
            var updated = await _students.GetByIdAsync(id, cancellationToken);
            return updated is null ? Missing("The student was not found.") : Ok(updated.ToDto());
        });
    }

    // API-15: all records of one student, active and returned, newest checkout first (UC-07, BR-14, BR-19).
    [HttpGet("{id}/borrowings")]
    [ProducesResponseType<List<BorrowingDto>>(StatusCodes.Status200OK)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status400BadRequest)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> History(int id, CancellationToken cancellationToken)
    {
        var history = await _borrowings.GetStudentHistoryAsync(id, cancellationToken);
        if (!history.SubjectFound) return Missing("The student was not found.");

        return Ok(history.Records.Select(r => r.ToDto()).ToList());
    }
}
