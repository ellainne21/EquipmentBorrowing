using EquipmentBorrowing.Application.Interfaces;
using EquipmentBorrowing.Application.Services;
using EquipmentBorrowing.Contracts;
using Microsoft.AspNetCore.Mvc;

namespace EquipmentBorrowing.Api.Controllers;

// API-01, API-07, API-08, API-09 and API-16. UC-01, 02, 08, 15, 16.
[ApiController]
[Route("api/v1/equipment")]
[Produces("application/json")]
[ProducesResponseType<ErrorResponse>(StatusCodes.Status500InternalServerError)]
public class EquipmentController : ApiControllerBase
{
    private readonly EquipmentQueryService _query;
    private readonly IEquipmentRepository _equipment;
    private readonly IBorrowingRepository _borrowings;
    private readonly RegisterEquipmentService _register;
    private readonly UpdateEquipmentService _update;

    public EquipmentController(
        EquipmentQueryService query,
        IEquipmentRepository equipment,
        IBorrowingRepository borrowings,
        RegisterEquipmentService register,
        UpdateEquipmentService update)
    {
        _query = query;
        _equipment = equipment;
        _borrowings = borrowings;
        _register = register;
        _update = update;
    }

    // API-01: all equipment, or only the available ones with ?available=true (UC-01, UC-02).
    // "search" is an optional extension to API-01 that keeps the Lab 4 catalog search working.
    // A value that is not true or false is a 400 (model binding).
    [HttpGet]
    [ProducesResponseType<List<EquipmentDto>>(StatusCodes.Status200OK)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status400BadRequest)]
    public async Task<IActionResult> List([FromQuery] string? search, [FromQuery] bool? available, CancellationToken cancellationToken)
    {
        var result = await _query.SearchAsync(search, available == true, cancellationToken);
        if (!result.IsSuccess) return ServerFailure(result.ErrorMessage);

        return Ok(result.Items.Select(e => e.ToDto()).ToList());
    }

    // API-07
    [HttpGet("{id}")]
    [ProducesResponseType<EquipmentDto>(StatusCodes.Status200OK)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status400BadRequest)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> Get(int id, CancellationToken cancellationToken)
    {
        var item = await _equipment.GetByIdAsync(id, cancellationToken);
        if (item is null) return Missing("The equipment item was not found.");

        return Ok(item.ToDto());
    }

    // API-08: a new item is available (BR-06). The id is generated by PostgreSQL.
    [HttpPost]
    [ProducesResponseType<EquipmentDto>(StatusCodes.Status201Created)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status400BadRequest)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status409Conflict)]
    public async Task<IActionResult> Create([FromBody] CreateEquipmentRequest request, CancellationToken cancellationToken)
    {
        var problem = RequiredText(request.EquipmentCode, "Equipment code", 50)
            ?? RequiredText(request.Name, "Name", 200)
            ?? OptionalText(request.Description, "Description", 500);
        if (problem is not null) return BadInput(problem);

        var result = await _register.ExecuteAsync(request.EquipmentCode, request.Name, request.Description, cancellationToken);
        if (!result.IsSuccess) return FromOperation(result);

        return await AfterSave(async () =>
        {
            var item = await _equipment.GetByIdAsync(result.EntityId!.Value, cancellationToken);
            if (item is null) return ServerFailure("The item was saved, but could not be read back. Refresh to see the current data.");

            return CreatedAtAction(nameof(Get), new { id = item.Id }, item.ToDto());
        });
    }

    // API-09: only descriptive fields. isAvailable is not part of the contract, so sending it is a 400 (BR-07).
    [HttpPut("{id}")]
    [ProducesResponseType<EquipmentDto>(StatusCodes.Status200OK)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status400BadRequest)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status404NotFound)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status409Conflict)]
    public async Task<IActionResult> Update(int id, [FromBody] UpdateEquipmentRequest request, CancellationToken cancellationToken)
    {
        var problem = RequiredText(request.EquipmentCode, "Equipment code", 50)
            ?? RequiredText(request.Name, "Name", 200)
            ?? OptionalText(request.Description, "Description", 500);
        if (problem is not null) return BadInput(problem);

        if (await _equipment.GetByIdAsync(id, cancellationToken) is null)
            return Missing("The equipment item was not found.");

        var result = await _update.ExecuteAsync(id, request.EquipmentCode, request.Name, request.Description, cancellationToken);
        if (!result.IsSuccess) return FromOperation(result);

        return await AfterSave(async () =>
        {
            var item = await _equipment.GetByIdAsync(id, cancellationToken);
            return item is null ? Missing("The equipment item was not found.") : Ok(item.ToDto());
        });
    }

    // API-16: all records of one item, active and returned, newest checkout first (UC-08, BR-14, BR-19).
    [HttpGet("{id}/borrowings")]
    [ProducesResponseType<List<BorrowingDto>>(StatusCodes.Status200OK)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status400BadRequest)]
    [ProducesResponseType<ErrorResponse>(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> History(int id, CancellationToken cancellationToken)
    {
        var history = await _borrowings.GetEquipmentHistoryAsync(id, cancellationToken);
        if (!history.SubjectFound) return Missing("The equipment item was not found.");

        return Ok(history.Records.Select(r => r.ToDto()).ToList());
    }
}