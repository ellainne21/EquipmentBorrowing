namespace EquipmentBorrowing.Domain;

public class Borrowing
{
    public int Id { get; private set; }               // generated by PostgreSQL
    public int StudentId { get; private set; }
    public int EquipmentId { get; private set; }
    public DateTime DateBorrowed { get; private set; }       // calendar date only
    public DateTime ExpectedReturnDate { get; private set; } // calendar date only
    public DateTime? ReturnedDate { get; private set; }      // actual return date (BR-13)
    public BorrowingStatus Status { get; private set; }

    // Used by EF Core when it reads rows from the database.
    private Borrowing() { }

    public Borrowing(int studentId, int equipmentId, DateTime checkoutDate, DateTime expectedReturnDate)
    {
        if (expectedReturnDate.Date <= checkoutDate.Date)
            throw new ArgumentException("Expected return date must be later than the checkout date.");

        StudentId = studentId;
        EquipmentId = equipmentId;
        DateBorrowed = checkoutDate.Date;
        ExpectedReturnDate = expectedReturnDate.Date;
        Status = BorrowingStatus.Active;
    }

    public void MarkAsReturned(DateTime returnedDate)
    {
        if (Status == BorrowingStatus.Returned)
            throw new InvalidOperationException("This borrowing has already been returned.");
        if (returnedDate.Date < DateBorrowed.Date)
            throw new ArgumentException("The return date cannot be before the checkout date.");

        ReturnedDate = returnedDate.Date;
        Status = BorrowingStatus.Returned;
    }
}